// @vitest-environment jsdom
import { cleanup, render, screen } from "@testing-library/react";
import { afterEach, beforeAll, describe, expect, it, vi } from "vitest";
import { AiPlanSection } from "@/components/landing/ai-plan-section";
import { stubMotionEnvironment } from "@/tests/motion-stubs";

beforeAll(() => {
  stubMotionEnvironment();
});

afterEach(cleanup);

afterEach(() => {
  vi.unstubAllGlobals();
});

describe("landing ai plan section", () => {
  it("pitches the guardrail promise with the checklist", () => {
    render(<AiPlanSection />);
    expect(screen.getByText("Zero Black-Box Executions")).toBeTruthy();
    expect(screen.getByText("Every recommendation can be edited")).toBeTruthy();
    expect(screen.getByText("Approve or reject the whole plan")).toBeTruthy();
    expect(screen.getByText("Nothing is deployed without your validation")).toBeTruthy();
  });

  it("renders the generated deployment manifest", () => {
    render(<AiPlanSection />);
    expect(screen.getByText("deployment.yaml")).toBeTruthy();
    expect(screen.getByText("Generated by AI")).toBeTruthy();
    expect(screen.getByText("apiVersion")).toBeTruthy();
    expect(screen.getByText("apps/v1")).toBeTruthy();
    expect(screen.getByText("apiVersion", { exact: false })).toBeTruthy();
    expect(screen.getByText("Syntax Validated")).toBeTruthy();
    expect(screen.getByText("UTF-8 · YAML · Kubernetes v1.29")).toBeTruthy();
  });
});
